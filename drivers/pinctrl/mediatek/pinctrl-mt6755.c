static int mt6755_adv_pull_set(struct mtk_pinctrl *hw,
			      const struct mtk_pin_desc *desc, bool pullup,
			      u32 arg)
{
	if (arg > 3)
		return -EINVAL;

	if (desc->number >= ARRAY_SIZE(mt6755_pull_type) ||
	    mt6755_pull_type[desc->number] != MTK_PULL_PUPD_R1R0_TYPE)
		return -ENOTSUPP;

	return mtk_pinconf_bias_set_combo(hw, desc, pullup,
					 MTK_PUPD_SET_R1R0_00 + arg);
}

